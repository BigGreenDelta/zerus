#!/usr/bin/env python3
"""Verify official inputs and apply the reviewed, exact-preimage CameraX backport."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import shutil
import zipfile


def verified(path, digest):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"CameraX input digest mismatch: {Path(path).name}")
    return data


def apply_patch(original, patch):
    lines = original.splitlines(keepends=True)
    result, cursor = [], 0
    for hunk in re.split(r"^@@", patch, flags=re.M)[1:]:
        header, body = hunk.split("\n", 1)
        match = re.fullmatch(r" -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@.*", header)
        if not match:
            raise ValueError("Invalid CameraX patch hunk")
        start = int(match[1]) - 1
        before = [line[1:] for line in body.splitlines(True) if line[:1] in (" ", "-")]
        after = [line[1:] for line in body.splitlines(True) if line[:1] in (" ", "+")]
        if start < cursor or lines[start:start + len(before)] != before:
            raise ValueError("CameraX patch preimage differs; offsets/fuzz are forbidden")
        result.extend(lines[cursor:start])
        result.extend(after)
        cursor = start + len(before)
    result.extend(lines[cursor:])
    return "".join(result)


def prepare(sources, aar, output):
    root = Path(__file__).resolve().parent
    pins = json.loads((root / "provenance.json").read_text())
    verified(sources, pins["sources_sha256"])
    verified(aar, pins["aar_sha256"])
    verified(root / "upstream.module.json", pins["module_sha256"])
    patch = verified(root / "patches/recorder-rebind-stop.patch", pins["patch_sha256"]).decode()
    output = Path(output)
    if output.exists():
        shutil.rmtree(output)
    java = output / "java"
    java.mkdir(parents=True)
    with zipfile.ZipFile(sources) as source_zip:
        if len(source_zip.namelist()) != pins["original_source_entries"]:
            raise ValueError("Unexpected official CameraX source inventory")
        for name in source_zip.namelist():
            path = Path(name)
            if path.is_absolute() or ".." in path.parts:
                raise ValueError("Unsafe source archive member")
            if name.endswith((".java", ".kt")):
                target = java / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(source_zip.read(name))
    recorder = java / "androidx/camera/video/Recorder.java"
    original = verified(recorder, pins["recorder_before_sha256"]).decode()
    patched = apply_patch(original, patch)
    if hashlib.sha256(patched.encode()).hexdigest() != pins["recorder_after_sha256"]:
        raise ValueError("CameraX patched Recorder digest mismatch")
    recorder.write_bytes(patched.encode())
    source_map = {}
    with zipfile.ZipFile(sources) as source_zip:
        for name in source_zip.namelist():
            if name.endswith((".java", ".kt")):
                source_map[name] = {"original": hashlib.sha256(source_zip.read(name)).hexdigest(),
                    "compiled_source": hashlib.sha256((java / name).read_bytes()).hexdigest()}
    (output / "source-map.json").write_text(json.dumps(source_map, indent=2) + "\n")
    with zipfile.ZipFile(aar) as original_aar:
        for name in original_aar.namelist():
            if name.startswith("res/") and not name.endswith("/"):
                target = output / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(original_aar.read(name))
        # AGP needs namespace in its DSL; the final AAR restores the exact official manifest.
        manifest = original_aar.read("AndroidManifest.xml").decode()
        (output / "AndroidManifest.xml").write_text(manifest.replace('    package="androidx.camera.video" ', ""))
        (output / "consumer-rules.pro").write_bytes(original_aar.read("proguard.txt"))
        resources = output / "resources"
        with zipfile.ZipFile(io.BytesIO(original_aar.read("classes.jar"))) as classes:
            # Kotlin module metadata is regenerated by the pinned compiler and checked separately.
            for name in classes.namelist():
                if not name.endswith((".class", ".kotlin_module", "/")):
                    destination = resources / name
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_bytes(classes.read(name))
        notices = resources / "META-INF/androidx/camera/camera-video"
        notices.mkdir(parents=True, exist_ok=True)
        (notices / "LICENSE.txt").write_bytes(original_aar.read("META-INF/androidx/camera/camera-video/LICENSE.txt"))
        (notices / "ZERUS_BACKPORT_NOTICE.txt").write_bytes((root / "NOTICE.txt").read_bytes())
    (output / "provenance.json").write_text(json.dumps(pins, indent=2) + "\n")


def repack(original, rebuilt, output):
    """Retain every official consumer/resource entry; replace source-built bytecode only."""
    pins = json.loads((Path(__file__).resolve().parent / "provenance.json").read_text())
    verified(original, pins["aar_sha256"])
    with zipfile.ZipFile(rebuilt) as built, zipfile.ZipFile(original) as upstream:
        # Canonical ZIP metadata avoids timestamps, traversal order and deflate-version inputs.
        jar = io.BytesIO()
        with zipfile.ZipFile(io.BytesIO(built.read("classes.jar"))) as source, zipfile.ZipFile(jar, "w") as target:
            for name in sorted(source.namelist()):
                info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
                info.external_attr = (0o40755 if name.endswith("/") else 0o100644) << 16
                target.writestr(info, source.read(name))
        classes = jar.getvalue()
        with zipfile.ZipFile(output, "w") as result:
            for name in sorted(upstream.namelist()):
                info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
                info.external_attr = (0o40755 if name.endswith("/") else 0o100644) << 16
                result.writestr(info, classes if name == "classes.jar" else upstream.read(name))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for command, names in [("prepare", ("sources", "aar", "output")), ("repack", ("original", "rebuilt", "output"))]:
        cmd = sub.add_parser(command)
        for name in names:
            cmd.add_argument("--" + name, required=True)
    args = vars(parser.parse_args())
    command = args.pop("command")
    (prepare if command == "prepare" else repack)(**args)
