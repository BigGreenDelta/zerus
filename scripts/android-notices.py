#!/usr/bin/env python3
"""Generate or check the Android app's notices for its shipped libraries.

The input is Gradle's report of the configuration the published APK is built from:

    cd mobile/android
    ./gradlew -q :app:dependencies --configuration releaseRuntimeClasspath \\
        -PzerusFirebase=true > deps.txt
    python3 ../../scripts/android-notices.py deps.txt            # rewrite the assets
    python3 ../../scripts/android-notices.py --check deps.txt    # fail on any difference

Libraries and POM files come from the Gradle cache (GRADLE_USER_HOME or ~/.gradle);
a POM missing there is downloaded from Google's Maven repository or Maven Central
unless --offline is given. Every library needs a recognized license, and every
library under a license other than Apache-2.0 or Google's SDK terms needs a
reviewed text in PROJECT_TEXTS, so an unreviewed dependency fails instead of
shipping without its notice.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import urllib.request
import xml.etree.ElementTree as ElementTree
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "mobile/android/app/src/main/assets/licenses"
REPOSITORIES = ("https://dl.google.com/android/maven2", "https://repo.maven.apache.org/maven2")
SDK_TERMS = "LicenseRef-Android-SDK"
# POM license names and URLs, normalized; anything else stops generation.
LICENSES = {
    "the apache software license, version 2.0": "Apache-2.0", "apache-2.0": "Apache-2.0",
    "the apache license, version 2.0": "Apache-2.0", "apache license, version 2.0": "Apache-2.0",
    "apache 2.0": "Apache-2.0", "apache license 2.0": "Apache-2.0",
    "bsd-2-clause": "BSD-2-Clause", "bsd-3-clause": "BSD-3-Clause", "mit license": "MIT", "the mit license": "MIT",
    "android software development kit license": SDK_TERMS,
}
# Reviewed license texts with the copyright notices of libraries whose license
# requires them (group or group:artifact -> asset file).
PROJECT_TEXTS = {
    "org.commonmark": "commonmark-java.txt",
    "org.nibor.autolink:autolink": "autolink-java.txt",
    "org.checkerframework:checker-qual": "checker-qual.txt",
    "androidx.datastore:datastore-preferences-external-protobuf": "protobuf.txt",
    # CameraX declares BSD-3-Clause for the libyuv code it contains.
    "androidx.camera:camera-core": "libyuv.txt",
}
GENERATED = ("libraries.tsv", "google-notices.txt", "library-notices.txt")
HEADER = "# Generated by scripts/android-notices.py from the release runtime classpath; do not edit.\n"


def coordinates(report):
    """Resolved group:artifact:version entries of a Gradle dependency report."""
    found, platforms = set(), set()
    for line in report.splitlines():
        match = re.match(r"^[|\\+ ]*[+\\]--- (.*)$", line.rstrip())
        if not match or match[1].endswith(" (c)"):
            continue
        if match[1].endswith(" (n)"):
            raise SystemExit("The report lists unresolved dependencies; report releaseRuntimeClasspath.")
        entry = re.sub(r" \(\*\)$", "", match[1])
        if entry.startswith("project "):
            continue
        requested, _, resolved = entry.partition(" -> ")
        if resolved.startswith("project "):
            continue  # A local module substituted for the library; its notices are reviewed by hand.
        parts = requested.split(":")
        version = resolved or (parts[2] if len(parts) > 2 else "")
        if len(parts) < 2 or not re.fullmatch(r"[\w.+-]+", version):
            raise SystemExit(f"Unresolved dependency in the report: {entry}")
        coordinate = (parts[0], parts[1], version)
        found.add(coordinate)
        if parts[1].endswith("-bom"):
            platforms.add(coordinate)
    if not found:
        raise SystemExit("The dependency report lists no libraries.")
    return sorted(found), platforms


class Libraries:
    def __init__(self, cache, offline):
        self.cache, self.offline = cache, offline

    def files(self, group, artifact, version):
        return sorted(self.cache.glob(f"{group}/{artifact}/{version}/*/*"))

    def pom(self, group, artifact, version):
        name = f"{artifact}-{version}.pom"
        for path in self.files(group, artifact, version):
            if path.name == name:
                return path.read_bytes()
        if self.offline:
            raise SystemExit(f"No POM for {group}:{artifact}:{version} in the Gradle cache.")
        for repository in REPOSITORIES:
            url = f"{repository}/{group.replace('.', '/')}/{artifact}/{version}/{name}"
            try:
                with urllib.request.urlopen(url, timeout=30) as response:
                    return response.read()
            except OSError:
                continue
        raise SystemExit(f"No POM for {group}:{artifact}:{version}.")

    def licenses(self, group, artifact, version, depth=0):
        """SPDX identifiers from the POM, or from its parents when it declares none."""
        root = ElementTree.fromstring(self.pom(group, artifact, version))
        namespace = root.tag[:root.tag.index("}") + 1] if root.tag.startswith("{") else ""

        def text(element, tag):
            child = element.find(namespace + tag)
            return (child.text or "").strip() if child is not None else ""
        found = []
        for license in root.findall(f"{namespace}licenses/{namespace}license"):
            name = text(license, "name")
            spdx = LICENSES.get(name.lower())
            if not spdx:
                raise SystemExit(f"Review the license '{name}' of {group}:{artifact}:{version}.")
            found.append(spdx)
        parent = root.find(namespace + "parent")
        if not found and parent is not None and depth < 5:
            return self.licenses(text(parent, "groupId"), text(parent, "artifactId"), text(parent, "version"), depth + 1)
        if not found:
            raise SystemExit(f"{group}:{artifact}:{version} declares no license.")
        return sorted(set(found))

    def archives(self, group, artifact, version):
        return [path for path in self.files(group, artifact, version)
                if path.suffix in (".aar", ".jar") and not path.stem.endswith(("-sources", "-javadoc"))]


def project_text(group, artifact):
    return PROJECT_TEXTS.get(f"{group}:{artifact}") or PROJECT_TEXTS.get(group)


def generate(report, cache, offline, assets=ASSETS):
    libraries = Libraries(cache, offline)
    entries, platforms = coordinates(report)
    rows, google, notices = [], {}, {}
    for group, artifact, version in entries:
        if (group, artifact, version) in platforms:
            rows.append(f"{group}:{artifact}:{version}\tplatform")
            continue
        licenses = libraries.licenses(group, artifact, version)
        text = project_text(group, artifact)
        if set(licenses) - {"Apache-2.0", SDK_TERMS} and not text:
            raise SystemExit(f"Add the reviewed {'/'.join(licenses)} text of {group}:{artifact} to PROJECT_TEXTS.")
        if text and not (assets / text).is_file():
            raise SystemExit(f"Missing reviewed license text {text}.")
        rows.append(f"{group}:{artifact}:{version}\t{' AND '.join(licenses)}" + (f"\t{text}" if text else ""))
        for archive in libraries.archives(group, artifact, version):
            with zipfile.ZipFile(archive) as bundle:
                names = set(bundle.namelist())
                # Google libraries list the open source code inside them here.
                if "third_party_licenses.json" in names:
                    index = json.loads(bundle.read("third_party_licenses.json") or b"{}")
                    body = bundle.read("third_party_licenses.txt")
                    for name, place in index.items():
                        content = body[place["start"]:place["start"] + place["length"]].decode("utf-8").strip()
                        google.setdefault(content, set()).add(name)
                for name in sorted(names):
                    if re.search(r"(^|/)NOTICE(\.[a-z]+)?$", name, re.IGNORECASE):
                        content = bundle.read(name).decode("utf-8").strip()
                        notices.setdefault(content, set()).add(f"{group}:{artifact} ({name})")
    # Each section starts with a "### names" line, which the app splits on.
    for content in [*google, *notices]:
        if re.search(r"(?m)^### ", content):
            raise SystemExit("A notice contains a line that starts a section; change the asset format.")
    sections = sorted((", ".join(sorted(names, key=str.lower)), content) for content, names in google.items())
    library_notices = sorted(("; ".join(sorted(names)), content) for content, names in notices.items())
    return {
        "libraries.tsv": HEADER + "\n".join(rows) + "\n",
        "google-notices.txt": "".join(f"### {names}\n\n{content}\n\n" for names, content in sections),
        "library-notices.txt": "".join(f"### {names}\n\n{content}\n\n" for names, content in library_notices),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("report", type=Path, help="output of gradlew :app:dependencies for releaseRuntimeClasspath")
    parser.add_argument("--check", action="store_true", help="compare with the assets instead of writing them")
    parser.add_argument("--offline", action="store_true", help="never download POM files")
    parser.add_argument("--assets", type=Path, default=ASSETS)
    args = parser.parse_args()
    home = Path(os.environ.get("GRADLE_USER_HOME") or Path.home() / ".gradle")
    outputs = generate(args.report.read_text(encoding="utf-8"), home / "caches/modules-2/files-2.1", args.offline,
                       args.assets)
    stale = [name for name, content in outputs.items()
             if not (args.assets / name).is_file() or (args.assets / name).read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            raise SystemExit("Android notices are out of date: " + ", ".join(stale)
                             + ". Regenerate them with scripts/android-notices.py.")
        print("Android library notices match the dependency report.")
        return
    for name in stale:
        (args.assets / name).write_text(outputs[name], encoding="utf-8")
    rows = outputs["libraries.tsv"].splitlines()[1:]
    platforms = sum(row.endswith("\tplatform") for row in rows)
    print(f"{len(rows) - platforms} libraries and {platforms} platforms; updated {', '.join(stale) or 'nothing'}.")


if __name__ == "__main__":
    sys.exit(main())
