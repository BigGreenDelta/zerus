#!/usr/bin/env python3
"""Generate or check the Android app's notices for its shipped libraries.

The input is the resolved configuration the published APK is built from, with the
exact artifact files Gradle resolved for it:

    cd mobile/android
    ./gradlew -q --init-script ../../scripts/android-resolved-artifacts.gradle \\
        -PzerusFirebase=true :app:zerusResolvedNotices
    python3 ../../scripts/android-notices.py            # rewrite the assets
    python3 ../../scripts/android-notices.py --check    # fail on any difference

Every shipped library must come with its artifact files, redirect to a resolved
library that has them, or be a metadata-only module; anything else stops before an
asset is written. POM files come from the Gradle cache (GRADLE_USER_HOME or
~/.gradle); a POM missing there is downloaded from Google's Maven repository or
Maven Central unless --offline is given. Every library needs a recognized license,
and every library under a license other than Apache-2.0 or Google's SDK terms needs
a reviewed text in PROJECT_TEXTS, so an unreviewed dependency fails instead of
shipping without its notice.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import urllib.request
import xml.etree.ElementTree as ElementTree
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "mobile/android/app/src/main/assets/licenses"
RESOLVED = ROOT / "mobile/android/app/build/zerus-notices/resolved.json"
CONFIGURATION = "releaseRuntimeClasspath"
# Local modules whose notices are reviewed by hand (THIRD_PARTY_NOTICES.md).
PROJECTS = {"project :camera-video-fixed"}
REPOSITORIES = ("https://dl.google.com/android/maven2", "https://repo.maven.apache.org/maven2")
SDK_TERMS = "LicenseRef-Android-SDK"
# POM license names and URLs, normalized; anything else stops generation.
LICENSES = {
    "the apache software license, version 2.0": "Apache-2.0", "apache-2.0": "Apache-2.0",
    "the apache license, version 2.0": "Apache-2.0", "apache license, version 2.0": "Apache-2.0",
    "apache 2.0": "Apache-2.0", "apache license 2.0": "Apache-2.0",
    "bsd-2-clause": "BSD-2-Clause", "bsd-3-clause": "BSD-3-Clause", "mit license": "MIT", "the mit license": "MIT",
    "android software development kit license": SDK_TERMS,
}
# Reviewed license texts with the copyright notices of libraries whose license
# requires them (group or group:artifact -> asset file).
PROJECT_TEXTS = {
    "org.commonmark": "commonmark-java.txt",
    "org.nibor.autolink:autolink": "autolink-java.txt",
    "org.checkerframework:checker-qual": "checker-qual.txt",
    "androidx.datastore:datastore-preferences-external-protobuf": "protobuf.txt",
    # CameraX declares BSD-3-Clause for the libyuv code it contains.
    "androidx.camera:camera-core": "libyuv.txt",
}
# Libraries offered under a choice of licenses (group:artifact -> the one the app
# uses). JNA, which the task replica's bindings load, is Apache-2.0 OR LGPL-2.1-or-later.
CHOSEN = {"net.java.dev.jna:jna": "Apache-2.0"}
HEADER = "# Generated by scripts/android-notices.py from the release runtime classpath; do not edit.\n"


def coordinate(identifier):
    return tuple(identifier.split(":"))


def platform(item):
    return set(item["categories"]) == {"platform"}


class Libraries:
    def __init__(self, cache, offline):
        self.cache, self.offline = cache, offline

    def files(self, group, artifact, version):
        return sorted(self.cache.glob(f"{group}/{artifact}/{version}/*/*"))

    def pom(self, group, artifact, version):
        name = f"{artifact}-{version}.pom"
        for path in self.files(group, artifact, version):
            if path.name == name:
                return path.read_bytes()
        if self.offline:
            raise SystemExit(f"No POM for {group}:{artifact}:{version} in the Gradle cache.")
        for repository in REPOSITORIES:
            url = f"{repository}/{group.replace('.', '/')}/{artifact}/{version}/{name}"
            try:
                with urllib.request.urlopen(url, timeout=30) as response:
                    return response.read()
            except OSError:
                continue
        raise SystemExit(f"No POM for {group}:{artifact}:{version}.")

    def licenses(self, group, artifact, version, depth=0):
        """SPDX identifiers from the POM, or from its parents when it declares none."""
        if f"{group}:{artifact}" in CHOSEN:
            return [CHOSEN[f"{group}:{artifact}"]]
        root = ElementTree.fromstring(self.pom(group, artifact, version))
        namespace = root.tag[:root.tag.index("}") + 1] if root.tag.startswith("{") else ""

        def text(element, tag):
            child = element.find(namespace + tag)
            return (child.text or "").strip() if child is not None else ""
        found = []
        for license in root.findall(f"{namespace}licenses/{namespace}license"):
            name = text(license, "name")
            spdx = LICENSES.get(name.lower())
            if not spdx:
                raise SystemExit(f"Review the license '{name}' of {group}:{artifact}:{version}.")
            found.append(spdx)
        parent = root.find(namespace + "parent")
        if not found and parent is not None and depth < 5:
            return self.licenses(text(parent, "groupId"), text(parent, "artifactId"), text(parent, "version"), depth + 1)
        if not found:
            raise SystemExit(f"{group}:{artifact}:{version} declares no license.")
        return sorted(set(found))

    def metadata_only(self, group, artifact, version):
        """Whether the cached Gradle metadata publishes no file in any variant."""
        name = f"{artifact}-{version}.module"
        for path in self.files(group, artifact, version):
            if path.name == name:
                variants = json.loads(path.read_text(encoding="utf-8")).get("variants") or []
                return bool(variants) and not any(variant.get("files") or variant.get("available-at")
                                                  for variant in variants)
        return False

    def components(self, resolved):
        """The validated components of the resolved release classpath, by identifier."""
        if resolved.get("configuration") != CONFIGURATION:
            raise SystemExit(f"Resolve {CONFIGURATION}, not {resolved.get('configuration')!r}.")
        unexpected = set(resolved.get("projects") or []) - PROJECTS
        if unexpected:
            raise SystemExit(f"Review the notices of local modules {sorted(unexpected)} first.")
        entries = {}
        for item in resolved.get("components") or []:
            identifier = item.get("id", "")
            parts = identifier.split(":")
            if len(parts) != 3 or not all(re.fullmatch(r"[\w.+-]+", part) for part in parts) or identifier in entries:
                raise SystemExit(f"Malformed or repeated resolved component {identifier!r}.")
            if set(item.get("categories") or []) not in ({"library"}, {"platform"}):
                raise SystemExit(f"{identifier} is neither only a library nor only a platform.")
            entries[identifier] = item
        if not entries:
            raise SystemExit("The resolved classpath lists no components.")
        for identifier, item in entries.items():
            files = [Path(name) for name in item.get("files") or []]
            if platform(item):
                if files:
                    raise SystemExit(f"Platform {identifier} ships files.")
                continue
            for path in files:
                if path.suffix not in (".aar", ".jar") or not path.is_file():
                    raise SystemExit(f"No artifact {path} of {identifier}; resolve the release classpath again.")
            if files or self.metadata_only(*coordinate(identifier)):
                continue
            # Kotlin multiplatform modules redirect to the variant that has the files.
            if not any(entries.get(target, {}).get("files") for target in item.get("redirects") or []):
                raise SystemExit(f"No artifact of {identifier}: it neither ships files nor redirects to a resolved"
                                 " library that does.")
        return entries


def project_text(group, artifact):
    return PROJECT_TEXTS.get(f"{group}:{artifact}") or PROJECT_TEXTS.get(group)


def generate(resolved, cache, offline, assets=ASSETS):
    libraries = Libraries(cache, offline)
    entries = libraries.components(resolved)
    rows, google, notices = [], {}, {}
    for identifier in sorted(entries, key=coordinate):
        group, artifact, version = coordinate(identifier)
        if platform(entries[identifier]):
            rows.append(f"{group}:{artifact}:{version}\tplatform")
            continue
        licenses = libraries.licenses(group, artifact, version)
        text = project_text(group, artifact)
        if set(licenses) - {"Apache-2.0", SDK_TERMS} and not text:
            raise SystemExit(f"Add the reviewed {'/'.join(licenses)} text of {group}:{artifact} to PROJECT_TEXTS.")
        if text and not (assets / text).is_file():
            raise SystemExit(f"Missing reviewed license text {text}.")
        rows.append(f"{group}:{artifact}:{version}\t{' AND '.join(licenses)}" + (f"\t{text}" if text else ""))
        for archive in entries[identifier].get("files") or []:
            with zipfile.ZipFile(archive) as bundle:
                names = set(bundle.namelist())
                # Google libraries list the open source code inside them here.
                if "third_party_licenses.json" in names:
                    index = json.loads(bundle.read("third_party_licenses.json") or b"{}")
                    body = bundle.read("third_party_licenses.txt")
                    for name, place in index.items():
                        content = body[place["start"]:place["start"] + place["length"]].decode("utf-8").strip()
                        google.setdefault(content, set()).add(name)
                for name in sorted(names):
                    if re.search(r"(^|/)NOTICE(\.[a-z]+)?$", name, re.IGNORECASE):
                        content = bundle.read(name).decode("utf-8").strip()
                        notices.setdefault(content, set()).add(f"{group}:{artifact} ({name})")
    # Each section starts with a "### names" line, which the app splits on.
    for content in [*google, *notices]:
        if re.search(r"(?m)^### ", content):
            raise SystemExit("A notice contains a line that starts a section; change the asset format.")
    sections = sorted((", ".join(sorted(names, key=str.lower)), content) for content, names in google.items())
    library_notices = sorted(("; ".join(sorted(names)), content) for content, names in notices.items())
    return {
        "libraries.tsv": HEADER + "\n".join(rows) + "\n",
        "google-notices.txt": "".join(f"### {names}\n\n{content}\n\n" for names, content in sections),
        "library-notices.txt": "".join(f"### {names}\n\n{content}\n\n" for names, content in library_notices),
    }


def replace(assets, outputs):
    """Stage every asset before replacing files atomically one at a time.

    A replacement failure propagates; rerun generation and --check to reconcile
    a partially replaced set. This is not a transaction across the asset files.
    """
    staged = {}
    try:
        for name, content in outputs.items():
            descriptor, path = tempfile.mkstemp(prefix=f".{name}.", dir=assets)
            staged[name] = Path(path)
            with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
                stream.write(content)
        for name, path in staged.items():
            os.replace(path, assets / name)
    finally:
        for path in staged.values():
            path.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("resolved", type=Path, nargs="?", default=RESOLVED,
                        help="resolved.json written by scripts/android-resolved-artifacts.gradle")
    parser.add_argument("--check", action="store_true", help="compare with the assets instead of writing them")
    parser.add_argument("--offline", action="store_true", help="never download POM files")
    parser.add_argument("--assets", type=Path, default=ASSETS)
    args = parser.parse_args()
    home = Path(os.environ.get("GRADLE_USER_HOME") or Path.home() / ".gradle")
    try:
        resolved = json.loads(args.resolved.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise SystemExit(f"Read the resolved release classpath first: {error}")
    outputs = generate(resolved, home / "caches/modules-2/files-2.1", args.offline, args.assets)
    stale = [name for name, content in outputs.items()
             if not (args.assets / name).is_file() or (args.assets / name).read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            raise SystemExit("Android notices are out of date: " + ", ".join(stale)
                             + ". Regenerate them with scripts/android-notices.py.")
        print("Android library notices match the resolved release classpath.")
        return
    replace(args.assets, {name: outputs[name] for name in stale})
    rows = outputs["libraries.tsv"].splitlines()[1:]
    platforms = sum(row.endswith("\tplatform") for row in rows)
    print(f"{len(rows) - platforms} libraries and {platforms} platforms; updated {', '.join(stale) or 'nothing'}.")


if __name__ == "__main__":
    sys.exit(main())
